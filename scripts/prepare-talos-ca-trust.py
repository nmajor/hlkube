#!/usr/bin/env python3
"""Produce a public Talos machine.files patch; never contacts or changes nodes."""
import argparse
import hashlib
import pathlib
import re
import ssl

BAD_ROOTS = {
    'd7a7a0fb5d7e2731d771e9484ebcdef71d5f0c3e0a2948782bc83ee0ea699ef4',
    '86a1ecba089c4a8d3bbe2734c612ba341d813e043cf9e8a862cd5c57a36bbe6b',
    '7dd78d5f4f13459a83dff9abbba62edbaf6f2d102bf257fd712f4d9f2746ed8d',
    'f2edaaff3d9b701fb4d14c9f285f8c0bad90fc3bcc1fa07d47f4718edaba34a5',
}
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('source', type=pathlib.Path)
p.add_argument('--output', required=True, type=pathlib.Path)
a = p.parse_args()
text = a.source.read_text()
if 'PRIVATE KEY' in text:
    p.error('Input must contain public certificates only.')
certs = re.findall(r'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', text, re.S)
if not certs:
    p.error('No certificates found.')
removed = []
def fingerprint(cert):
    return hashlib.sha256(ssl.PEM_cert_to_DER_cert(cert)).hexdigest()
def replace(m):
    digest = fingerprint(m.group())
    if digest in BAD_ROOTS:
        removed.append(digest)
        return ''
    return m.group()
fixed = re.sub(r'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', replace, text, flags=re.S)
kept = re.findall(r'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', fixed, re.S)
if not removed or not kept:
    p.error('Expected affected roots and a nonempty replacement bundle.')
assert {fingerprint(c) for c in kept} == {fingerprint(c) for c in certs} - BAD_ROOTS
patch = ('# Public CA certificates only. Generated by scripts/prepare-talos-ca-trust.py.\n'
         'machine:\n  files:\n    - path: /etc/ssl/certs/ca-certificates.crt\n'
         '      op: overwrite\n      permissions: 0o644\n      content: |\n')
patch += ''.join(('        '+line if line else '')+'\n' for line in fixed.splitlines())
a.output.write_text(patch)
print(f'Removed {len(removed)} affected roots; preserved {len(kept)} certificates.')
print('Source SHA256:', hashlib.sha256(text.encode()).hexdigest())
print('Replacement SHA256:', hashlib.sha256(fixed.encode()).hexdigest())
